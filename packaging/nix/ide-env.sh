#!/usr/bin/env bash
# Print the dev shell's environment in a form RustRover/IntelliJ can consume.
#
#   ./packaging/nix/ide-env.sh          KEY=VALUE lines -> paste into
#                                       Settings > Toolchain > Environment variables
#   ./packaging/nix/ide-env.sh --cargo  a [env] block for src-tauri/.cargo/config.toml
#
# The values are Nix store paths, so regenerate this whenever flake.lock changes.
#
# NOTE: the generated src-tauri/.cargo/config.toml is gitignored AND is pruned
# from the Nix source copy (packaging/nix/lib.nix). Never let it into a Nix
# build: cargo applies those `[env] force = true` entries to build scripts, so
# the sandbox would get this host's PKG_CONFIG_PATH instead of the derivation's,
# and the webkit/sys crates fail to find their .pc files.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
mode="${1:-}"

# Evaluated INSIDE the dev shell, so shellHook contributions are included.
dump="$(nix develop "$here" -c bash -c '
  for v in PKG_CONFIG_PATH LD_LIBRARY_PATH XDG_DATA_DIRS GIO_EXTRA_MODULES \
           GST_PLUGIN_SYSTEM_PATH_1_0; do
    printf "%s=%s\n" "$v" "${!v}"
  done
  # pkg-config itself has to be on PATH for the sys crates to link.
  printf "PATH=%s\n" "$PATH"
')"

case "$mode" in
  --cargo)
    echo '# Generated by packaging/nix/ide-env.sh - regenerate after "nix flake update".'
    echo '# Keeps plain `cargo check` / rust-analyzer working outside `nix develop`.'
    echo "[env]"
    while IFS= read -r line; do
      key="${line%%=*}"; val="${line#*=}"
      [ "$key" = PATH ] && continue   # clobbering PATH in cargo config is rarely what you want
      printf '  %s = { value = "%s", force = true }\n' "$key" "$val"
    done <<<"$dump"
    ;;
  *)
    printf '%s\n' "$dump"
    ;;
esac
